from pathlib import Path
import threading, http.server, functools
from playwright.sync_api import sync_playwright
base=Path('/mnt/data/XORA_PHASE1')
handler=functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(base/'prototype'))
server=http.server.ThreadingHTTPServer(('127.0.0.1',8765),handler)
threading.Thread(target=server.serve_forever,daemon=True).start()
url='http://127.0.0.1:8765/index.html'
errs=[]
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
 page.on('pageerror',lambda e:errs.append(str(e)))
 page.goto(url)
 print('home',page.title(),page.locator('h1').first.inner_text())
 page.screenshot(path=str(base/'screenshots/01-desktop-landing.png'),full_page=True)
