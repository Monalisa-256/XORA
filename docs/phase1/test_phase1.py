 page.get_by_role('button',name='Membership',exact=True).first.click()
 print('member status',page.get_by_text('Active',exact=True).count())
 # mobile
 mobile=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1, is_mobile=True,has_touch=True)
 mobile.on('pageerror',lambda e:errs.append(str(e)))
 mobile.goto(url)
 mobile.screenshot(path=str(base/'screenshots/05-mobile-landing.png'),full_page=True)
 mobile.get_by_role('button',name='Explore demo').click()
 mobile.screenshot(path=str(base/'screenshots/06-mobile-discover.png'),full_page=True)
 print('mobile horizontal overflow',mobile.evaluate('document.documentElement.scrollWidth > window.innerWidth'))
 browser.close()
