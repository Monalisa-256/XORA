 # open first profile and free invitation
 page.get_by_role('button',name='View profile').first.click()
 print('person',page.locator('h1').first.inner_text())
 page.get_by_role('button',name='Say Hello').click()
 print('invitations',page.locator('h1').first.inner_text())
 page.get_by_role('button',name='Simulate acceptance').click()
